/**
 * T066 — build a self-hosted Lucide sprite at public/icons/lucide.svg.
 *
 * The design system substitutes Lucide 0.460.0 via CDN and flags the substitution (ui-conflicts
 * C-07). Production self-hosts it: the strict Content-Security-Policy admits no third-party origin,
 * and PDPL rules out a per-page-view call to someone else's server. The version is pinned in
 * package.json, so the sprite is reproducible rather than whatever the CDN served that day.
 *
 * Only the icons the platform actually renders are included — a sprite containing all 1,500 Lucide
 * icons would be roughly 1.5 MB on every page load to use forty of them. Adding an icon means
 * adding a name here, which is also the review point: the set stays deliberate.
 *
 * Stroke 1.75 with round caps, per design-system.md §7: the brand board shows a bespoke outline set
 * at ~1.75px, and Lucide's own default of 2 reads visibly heavier beside Cairo.
 *
 * Idempotent. Run with `npm run build:icons`.
 */
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import { constants } from 'node:fs';

const SOURCE = 'node_modules/lucide-static/icons';
const TARGET = 'public/icons/lucide.svg';
const STROKE_WIDTH = '1.75';

/**
 * Grouped only for readability — the sprite is flat.
 *
 * The navigation group is the design-system.md §7 name map verbatim, including v2's correction of
 * البرامج from `graduation-cap` to `library` (v2 reassigns `graduation-cap` to الطلبة).
 */
const ICONS = {
    navigation: [
        'house', 'layout-dashboard', 'chart-pie', 'lightbulb', 'building-2', 'library',
        'book-open', 'users', 'user-cog', 'calendar-range', 'file-up', 'shield-check',
        'chart-column', 'settings', 'graduation-cap', 'user', 'headphones',
    ],
    status: [
        'check', 'circle-check', 'circle-alert', 'circle-x', 'triangle-alert', 'info',
        'loader-circle', 'timer', 'inbox', 'ban',

        // US2's two refusal pages (T152). Named by the task, and absent from the sprite until the
        // 403 baseline was looked at: an unknown name renders nothing at all, so the page came out
        // correct in every respect except the icon that was supposed to carry its meaning.
        'shield-off', 'file-question',
    ],
    direction: [
        'chevron-down', 'chevron-up', 'chevron-left', 'chevron-right',
        'chevrons-left', 'chevrons-right', 'arrow-up', 'arrow-down', 'arrow-up-down',
    ],
    actions: [
        'plus', 'pencil', 'trash-2', 'copy', 'download', 'upload', 'search', 'filter',
        'x', 'menu', 'log-out', 'rotate-cw', 'rotate-ccw', 'repeat', 'share-2',
        'ellipsis', 'ellipsis-vertical', 'external-link', 'eye', 'eye-off',
    ],
    people: [
        'user-plus', 'user-minus', 'user-x', 'key-round', 'lock', 'mail', 'bell',
        'circle-help',
    ],
    academic: [
        'calendar-days', 'calendar-plus', 'clipboard-list', 'file-spreadsheet',
        'folder-open', 'award', 'medal', 'star', 'flask-conical', 'scan-search',
        'map-pin', 'mouse-pointer-click',
    ],
};

try {
    await access(SOURCE, constants.R_OK);
} catch {
    console.error('\n  lucide-static is not installed. Run `npm install` first.\n');
    process.exit(1);
}

const names = [...new Set(Object.values(ICONS).flat())].sort();
const symbols = [];
const missing = [];

for (const name of names) {
    let svg;

    try {
        svg = await readFile(`${SOURCE}/${name}.svg`, 'utf8');
    } catch {
        missing.push(name);
        continue;
    }

    // Everything between the <svg> wrapper is the geometry. The wrapper's own presentation
    // attributes are re-declared on the <symbol> so one sprite-wide change reaches every icon.
    const inner = svg
        .replace(/^[\s\S]*?<svg[^>]*>/, '')
        .replace(/<\/svg>\s*$/, '')
        .replace(/\s+/g, ' ')
        .trim();

    if (inner === '') {
        missing.push(name);
        continue;
    }

    symbols.push(
        `  <symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
        `stroke-width="${STROKE_WIDTH}" stroke-linecap="round" stroke-linejoin="round">` +
        `${inner}</symbol>`
    );
}

if (missing.length > 0) {
    console.error(`\n  These icon names do not exist in Lucide 0.460.0:\n    ${missing.join(', ')}\n`);
    process.exit(1);
}

const sprite =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!--\n` +
    `  T066 — GENERATED by scripts/build-icons.mjs; do not edit by hand.\n` +
    `  Lucide 0.460.0, ${symbols.length} icons, stroke ${STROKE_WIDTH}, round caps.\n` +
    `  Add an icon by adding its name to ICONS in the script, then re-running it.\n` +
    `-->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n` +
    symbols.join('\n') +
    `\n</svg>\n`;

await mkdir('public/icons', { recursive: true });
await writeFile(TARGET, sprite, 'utf8');

console.log(`  icons: ${symbols.length} symbols -> ${TARGET} (${(sprite.length / 1024).toFixed(1)} KB)`);
