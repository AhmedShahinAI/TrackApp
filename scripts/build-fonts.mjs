/**
 * T058 + T059 — self-host Cairo and Inter, and generate the @font-face layer from the pinned
 * packages rather than by hand.
 *
 * The design system's tokens/fonts.css loads both families from Google Fonts. Production cannot:
 * the constitution's strict Content-Security-Policy admits no third-party origin, and PDPL means
 * the platform must not hand every page view to another operator. So the files are vendored and
 * served from our own root.
 *
 * Generated rather than written out by hand because each @font-face needs an exact unicode-range,
 * and there are fourteen of them. A hand-copied range that is subtly wrong does not fail loudly —
 * it silently stops a glyph subset from loading, and the browser falls back to a system font for
 * exactly the characters nobody on the team happens to type.
 *
 * Idempotent. Run with `npm run build:fonts`.
 */
import { mkdir, copyFile, writeFile, readFile, access } from 'node:fs/promises';
import { constants } from 'node:fs';

const TARGET_DIR = 'public/fonts';
const CSS_OUT = 'resources/css/tokens/fonts.css';

/**
 * Only `arabic` and `latin`. `latin-ext` carries accented European glyphs that an Arabic/English
 * academic interface never renders, and every subset shipped is a file the browser may fetch.
 * The `latin` range includes U+0000-00FF, which is where the Western digits 0-9 live — FR-084
 * requires those in both locales, so the numeral subset is not a separate concern.
 */
const FAMILIES = [
    { family: 'Cairo', pkg: '@fontsource/cairo', slug: 'cairo', weights: [400, 500, 600, 700, 800], subsets: ['arabic', 'latin'] },
    { family: 'Inter', pkg: '@fontsource/inter', slug: 'inter', weights: [400, 500, 600, 700], subsets: ['latin'] },
];

/** Read the unicode-range for one subset out of the package's own CSS, so it cannot drift. */
async function unicodeRanges(pkg, weight) {
    const css = await readFile(`node_modules/${pkg}/${weight}.css`, 'utf8');
    const ranges = {};

    // Each block is preceded by a comment naming the subset: /* cairo-arabic-400-normal */
    const blocks = css.split('@font-face');

    for (const block of blocks) {
        const subset = block.match(/\/files\/[a-z]+-([a-z-]+)-\d+-normal\.woff2/);
        const range = block.match(/unicode-range:\s*([^;]+);/);

        if (subset && range) {
            ranges[subset[1]] = range[1].trim();
        }
    }

    return ranges;
}

try {
    await access('node_modules/@fontsource/cairo', constants.R_OK);
} catch {
    console.error('\n  Font packages are not installed. Run `npm install` first.\n');
    process.exit(1);
}

await mkdir(TARGET_DIR, { recursive: true });

const faces = [];
let copied = 0;

for (const { family, pkg, slug, weights, subsets } of FAMILIES) {
    for (const weight of weights) {
        const ranges = await unicodeRanges(pkg, weight);

        for (const subset of subsets) {
            const file = `${slug}-${subset}-${weight}-normal.woff2`;

            await copyFile(`node_modules/${pkg}/files/${file}`, `${TARGET_DIR}/${file}`);
            copied++;

            if (!ranges[subset]) {
                throw new Error(`No unicode-range for ${slug} ${subset} ${weight} in ${pkg}/${weight}.css`);
            }

            faces.push(
                `/* ${family} ${weight} · ${subset} */\n` +
                `@font-face {\n` +
                `    font-family: '${family}';\n` +
                `    font-style: normal;\n` +
                `    font-weight: ${weight};\n` +
                `    font-display: swap;\n` +
                `    src: url('/fonts/${file}') format('woff2');\n` +
                `    unicode-range: ${ranges[subset]};\n` +
                `}`
            );
        }
    }
}

const header = `/*
 * T058 — self-hosted Cairo and Inter. GENERATED by scripts/build-fonts.mjs; do not edit by hand.
 *
 * Replaces the design system's Google Fonts @import (design-system/tokens/fonts.css). The strict
 * Content-Security-Policy admits no third-party origin, and PDPL forbids handing every page view to
 * another operator.
 *
 * font-display: swap everywhere — Arabic text rendered in a fallback for 100ms is a far smaller
 * problem than a blank screen, and Cairo's metrics are close enough to the system Arabic face that
 * the swap does not reflow badly.
 *
 * Preload hints for the two above-the-fold weights live in layouts/app.blade.php, not here: a
 * stylesheet cannot preload itself early enough to matter.
 */

`;

await writeFile(CSS_OUT, header + faces.join('\n\n') + '\n', 'utf8');

console.log(`  fonts: ${copied} woff2 files -> ${TARGET_DIR}`);
console.log(`  fonts: ${faces.length} @font-face blocks -> ${CSS_OUT}`);
