<?php

declare(strict_types=1);

use App\Models\Section;
use Illuminate\Database\QueryException;

/*
|--------------------------------------------------------------------------
| Checkpoint A — conditional uniqueness on the section key (T471, FR-176)
|--------------------------------------------------------------------------
|
| The section key is unique among sections that are *not* rejected. MySQL has no partial index, so
| the schema carries a stored generated column that collapses to NULL for a rejected row, and the
| unique index covers that column. NULLs do not collide, so rejected rows coexist and release their
| number back.
|
| This is the one piece of the schema whose correctness is not readable from the migration, which is
| why it has its own test. data-model.md Group 8 explains why each simpler alternative fails.
|
*/

/**
 * One term, branch, course, programme, and creator, shared by every section in a test.
 *
 * The uniqueness is on the combination, so the other four columns have to be held constant for a
 * collision to be about the section number and nothing else.
 *
 * @return array<string, int|null>
 */
function sharedSectionKey(): array
{
    $base = Section::factory()->create(['section_number' => '001']);

    return [
        'term_id' => $base->term_id,
        'branch_id' => $base->branch_id,
        'course_id' => $base->course_id,
        'program_id' => $base->program_id,
        'created_by' => $base->created_by,
        'instructor_id' => null,
    ];
}

/**
 * @param  array<string, int|null>  $shared
 */
function sectionWith(string $number, string $status, array $shared): Section
{
    $section = Section::factory()->make(array_merge($shared, [
        'section_number' => $number,
        'status' => $status,
        'requires_approval' => $status !== 'active',
    ]));

    $section->save();

    return $section;
}

test('two live sections cannot share a number', function (): void {
    $shared = sharedSectionKey();

    sectionWith('123', 'active', $shared);

    expect(fn (): Section => sectionWith('123', 'active', $shared))
        ->toThrow(QueryException::class);
});

test('a pending section cannot take a live number', function (): void {
    $shared = sharedSectionKey();

    sectionWith('123', 'active', $shared);

    // `pending` is not `rejected`, so its approval_key is the number and it collides. A section
    // awaiting approval has reserved the number — that is the point of FR-176.
    expect(fn (): Section => sectionWith('123', 'pending', $shared))
        ->toThrow(QueryException::class);
});

test('rejecting a section releases its number', function (): void {
    $shared = sharedSectionKey();

    $first = sectionWith('123', 'pending', $shared);

    $first->forceFill(['status' => 'rejected'])->save();
    $first->refresh();

    expect($first->approval_key)->toBeNull();

    // The number is free again, which is the behaviour a coordinator expects after refusing a
    // duplicate request.
    $second = sectionWith('123', 'active', $shared);

    // fresh(), because approval_key is generated by the database: the value is never in the
    // in-memory model after an insert, only in the row.
    expect($second->exists)->toBeTrue()
        ->and($second->fresh()->approval_key)->toBe('123');
});

test('any number of rejected sections may share a number', function (): void {
    $shared = sharedSectionKey();

    foreach (range(1, 3) as $ignored) {
        $section = sectionWith('777', 'pending', $shared);
        $section->forceFill(['status' => 'rejected'])->save();
    }

    expect(Section::query()->where('section_number', '777')->where('status', 'rejected')->count())
        ->toBe(3);

    // And exactly one live section can still exist alongside them.
    sectionWith('777', 'active', $shared);

    expect(Section::query()->where('section_number', '777')->where('status', '!=', 'rejected')->count())
        ->toBe(1);
});

test('the same number is free in another branch', function (): void {
    $shared = sharedSectionKey();

    sectionWith('123', 'active', $shared);

    // FR-041: the key is term + branch + course + number. Two campuses running the same course both
    // call their first section 123, and neither is wrong.
    $elsewhere = Section::factory()->create(array_merge($shared, [
        'branch_id' => Section::factory()->create()->branch_id,
        'section_number' => '123',
    ]));

    expect($elsewhere->exists)->toBeTrue();
});

test('approval_key is generated by the database, not by application code', function (): void {
    $section = sectionWith('456', 'active', sharedSectionKey());

    // Never assigned anywhere in the application. If this were a normal column someone would have
    // to remember to maintain it on every write, and the index would silently stop meaning anything
    // the first time somebody forgot.
    expect($section->fresh()->approval_key)->toBe('456');

    $section->forceFill(['status' => 'rejected'])->save();

    expect($section->fresh()->approval_key)->toBeNull();
});
